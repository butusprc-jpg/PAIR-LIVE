import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {Pool} from 'pg';
import {assertTestTarget,migrationManifest} from '../lib/migration-manifest';
import {createTopup,decideTopup} from '../lib/topup/store';
import {createWithdrawal,decideWithdrawal} from '../lib/withdrawal/store';
import {memberAvailablePoints} from '../lib/server/wallet-cutover';
import {processTopupPostback} from '../lib/topup/line-postback';
import {processWithdrawalPostback} from '../lib/withdrawal/line';

const raw=process.env.TOPUP_TEST_DATABASE_URL;
test('wallet cutover topup and withdrawal use one ledger mutation per request, including predebit refund and rollback',{skip:!raw},async()=>{
 const adminPool=new Pool({connectionString:assertTestTarget(raw)});
 const schema='topup_wallet_'+randomUUID().replaceAll('-','');
 const oldGate=process.env.PAIR_WALLET_CUTOVER_VERIFIED,oldLogin=process.env.LINE_LOGIN_CHANNEL_ID,oldToken=process.env.LINE_MESSAGING_CHANNEL_ACCESS_TOKEN;
 let db:Pool|undefined;
 try{
  await adminPool.query(`CREATE SCHEMA ${schema}`);
  const url=new URL(raw!);url.searchParams.set('options',`-csearch_path=${schema}`);
  db=new Pool({connectionString:url.toString(),max:12});
  for(const migration of await migrationManifest())await db.query(migration.sql);
  const member=(await db.query("INSERT INTO members(display_name,demo_points) VALUES('Wallet cutover fixture',600) RETURNING id")).rows[0].id as string;
  const adminLine='U'+'a'.repeat(32);
  const admin=(await db.query("INSERT INTO admin_identities(provider,provider_channel_id,provider_user_id,display_name) VALUES('line','test',$1,'Admin') RETURNING id",[adminLine])).rows[0].id as string;
  // Model an old request that held 100 points before the wallet snapshot.
  const legacy=(await db.query("INSERT INTO member_withdrawal_requests(member_id,requested_points,payout_details,idempotency_key,debit_timing) VALUES($1,100,'old PREDEBIT',$2,'PREDEBIT') RETURNING id",[member,randomUUID()])).rows[0];
  await db.query('UPDATE members SET demo_points=500 WHERE id=$1',[member]);
  await db.query('INSERT INTO member_wallets(member_id,available_points) VALUES($1,500)',[member]);
  await db.query("UPDATE member_wallet_runtime_state SET phase='CUTOVER_PENDING' WHERE id=1");
  await db.query("UPDATE member_wallet_runtime_state SET phase='WALLET_ACTIVE',enabled=true,ever_cutover=true,cutover_at=now() WHERE id=1");
  process.env.PAIR_WALLET_CUTOVER_VERIFIED='true';
  process.env.LINE_LOGIN_CHANNEL_ID='test';process.env.LINE_MESSAGING_CHANNEL_ACCESS_TOKEN='synthetic-test-token';
  const allowlist=JSON.stringify([{userId:adminLine,role:'admin'}]);
  const delivered:{to:string;body:string}[]=[];
  const fetchLine:typeof fetch=async(_url,init)=>{const payload=JSON.parse(String(init?.body));delivered.push({to:payload.to,body:JSON.stringify(payload.messages)});return new Response('',{status:200})};
  const balance=async()=>Number((await db!.query('SELECT available_points FROM member_wallets WHERE member_id=$1',[member])).rows[0].available_points);
  const topup=await createTopup(db,member,40,randomUUID());
  assert.equal(topup.status,'PENDING');assert.equal(await balance(),500);
  const approved=await processTopupPostback(db,{webhookEventId:'wallet-topup-approval',type:'postback',userId:adminLine,data:`topup:v2:review:APPROVED:${topup.id}`},{allowlist,fetch:fetchLine});
  assert.equal(approved.result,'APPROVED');
  assert.equal((await processTopupPostback(db,{webhookEventId:'wallet-topup-approval',type:'postback',userId:adminLine,data:`topup:v2:review:APPROVED:${topup.id}`},{allowlist,fetch:fetchLine})).duplicate,true);
  await Promise.all(Array.from({length:4},()=>decideTopup(db!,admin,topup.id,'APPROVED','synthetic')));
  assert.equal(await balance(),540);
  assert.equal((await db.query('SELECT count(*)::int n FROM member_wallet_ledger WHERE reference_id=$1',[topup.id])).rows[0].n,1);
  await assert.rejects(decideTopup(db,admin,randomUUID(),'APPROVED','synthetic'),/not_found/);
  assert.equal(await balance(),540);
  const withdraw=await createWithdrawal(db,member,60,'new ON_APPROVAL',randomUUID(),['U'+'a'.repeat(32)]);
  assert.equal(withdraw.debit_timing,'ON_APPROVAL');assert.equal(await balance(),540);
  assert.equal((await processWithdrawalPostback(db,{webhookEventId:'wallet-withdraw-approval',userId:adminLine,data:`withdraw:v1:transfer:${withdraw.id}`},{allowlist,fetch:fetchLine})).result,'TRANSFERRED');
  assert.deepEqual(await processWithdrawalPostback(db,{webhookEventId:'wallet-withdraw-approval',userId:adminLine,data:`withdraw:v1:transfer:${withdraw.id}`},{allowlist,fetch:fetchLine}),{result:'TRANSFERRED',replayed:true,points:60,debit_timing:'ON_APPROVAL'});
  await Promise.all(Array.from({length:4},()=>decideWithdrawal(db!,admin,withdraw.id,'TRANSFERRED')));
  assert.equal(await balance(),480);
  assert.equal((await db.query('SELECT count(*)::int n FROM member_wallet_ledger WHERE reference_id=$1',[withdraw.id])).rows[0].n,1);
  assert.ok(delivered.some(x=>x.to===adminLine&&x.body.includes('อนุมัติแล้ว')));
  const rejected=await createWithdrawal(db,member,30,'reject',randomUUID(),['U'+'a'.repeat(32)]);
  await decideWithdrawal(db,admin,rejected.id,'REJECTED');assert.equal(await balance(),480);
  assert.equal((await db.query('SELECT count(*)::int n FROM member_wallet_ledger WHERE reference_id=$1',[rejected.id])).rows[0].n,0);
  await decideWithdrawal(db,admin,legacy.id,'REJECTED');
  await decideWithdrawal(db,admin,legacy.id,'REJECTED');
  assert.equal(await balance(),580);
  assert.equal((await db.query('SELECT count(*)::int n FROM member_wallet_ledger WHERE reference_id=$1',[legacy.id])).rows[0].n,1);
  assert.equal(await memberAvailablePoints(db,member,500),580);
  assert.equal((await db.query('SELECT demo_points FROM members WHERE id=$1',[member])).rows[0].demo_points,500);
  const insufficient=await createWithdrawal(db,member,580,'insufficient later',randomUUID(),['U'+'a'.repeat(32)]);
  const reduce=await createWithdrawal(db,member,100,'reduce',randomUUID(),['U'+'a'.repeat(32)]);
  await decideWithdrawal(db,admin,reduce.id,'TRANSFERRED');
  await assert.rejects(decideWithdrawal(db,admin,insufficient.id,'TRANSFERRED'),/withdrawal_insufficient_points/);
  assert.equal(await balance(),480);
  const failed=await createTopup(db,member,20,randomUUID());
  await db.query("CREATE FUNCTION fail_wallet_topup_audit() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'synthetic_topup_audit_failed'; END $$");
  await db.query('CREATE TRIGGER fail_wallet_topup_audit BEFORE INSERT ON member_topup_audit FOR EACH ROW EXECUTE FUNCTION fail_wallet_topup_audit()');
  await assert.rejects(decideTopup(db,admin,failed.id,'APPROVED',''),/synthetic_topup_audit_failed/);
  assert.equal(await balance(),480);
  assert.equal((await db.query('SELECT count(*)::int n FROM member_wallet_ledger WHERE reference_id=$1',[failed.id])).rows[0].n,0);
  assert.equal((await db.query('SELECT status FROM member_topup_requests WHERE id=$1',[failed.id])).rows[0].status,'PENDING');
  await db.query('DROP TRIGGER fail_wallet_topup_audit ON member_topup_audit');
  await decideTopup(db,admin,failed.id,'APPROVED','');assert.equal(await balance(),500);
  const failedWithdrawal=await createWithdrawal(db,member,25,'rollback debit',randomUUID(),['U'+'a'.repeat(32)]);
  await db.query("CREATE FUNCTION fail_wallet_withdrawal_audit() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'synthetic_withdrawal_audit_failed'; END $$");
  await db.query('CREATE TRIGGER fail_wallet_withdrawal_audit BEFORE INSERT ON member_withdrawal_audit FOR EACH ROW EXECUTE FUNCTION fail_wallet_withdrawal_audit()');
  await assert.rejects(decideWithdrawal(db,admin,failedWithdrawal.id,'TRANSFERRED'),/synthetic_withdrawal_audit_failed/);
  assert.equal(await balance(),500);
  assert.equal((await db.query('SELECT count(*)::int n FROM member_wallet_ledger WHERE reference_id=$1',[failedWithdrawal.id])).rows[0].n,0);
  await db.query('DROP TRIGGER fail_wallet_withdrawal_audit ON member_withdrawal_audit');
  await decideWithdrawal(db,admin,failedWithdrawal.id,'TRANSFERRED');assert.equal(await balance(),475);
 }finally{
  if(oldGate===undefined)delete process.env.PAIR_WALLET_CUTOVER_VERIFIED;else process.env.PAIR_WALLET_CUTOVER_VERIFIED=oldGate;
  if(oldLogin===undefined)delete process.env.LINE_LOGIN_CHANNEL_ID;else process.env.LINE_LOGIN_CHANNEL_ID=oldLogin;
  if(oldToken===undefined)delete process.env.LINE_MESSAGING_CHANNEL_ACCESS_TOKEN;else process.env.LINE_MESSAGING_CHANNEL_ACCESS_TOKEN=oldToken;
  await db?.end();await adminPool.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);await adminPool.end();
 }
});
